#!/usr/bin/env node
/* eslint-disable @typescript-eslint/explicit-function-return-type */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(new URL('../package.json', import.meta.url)));
const outDir = join(root, 'docs/.vitepress/theme/generated');

function runPnpm(args) {
  execFileSync('pnpm', args, {
    cwd: root,
    stdio: 'inherit'
  });
}

function ensureWorkspaceBuilds() {
  if (!existsSync(join(root, 'packages/core/dist/index.js'))) {
    runPnpm(['build:core']);
  }

  if (!existsSync(join(root, 'packages/tokens/dist/index.js'))) {
    runPnpm(['build:tokens']);
  }
}

function dkJson(args) {
  const stdout = execFileSync(process.execPath, [join(root, 'bin/dk.js'), ...args, '--json'], {
    cwd: root,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe']
  });
  return JSON.parse(stdout);
}

ensureWorkspaceBuilds();

const seed = '#D96F32';
const perfect = dkJson(['perfect', '--seed', seed, '--ratio', 'perfect-fourth', '--motion', 'snappy', '--mode', 'light']);
const palette = dkJson(['palette', seed, '--harmony', 'split-complementary']);
const scale = dkJson(['scale', '--fluid', '--ratio', 'perfect-fourth', '--base-min', '15', '--base-max', '19']);
const text = dkJson(['text', '--font', '18', '--measure', '680', '--contrast', '72', '--profile', 'default']);
const target = dkJson(['target', '--distance', '280', '--width', '44', '--choices', '6', '--modality', 'touch']);

const tones = palette.colors.reduce((acc, color) => {
  acc[color.label] = Object.fromEntries(Object.entries(color.tonal).map(([tone, value]) => [tone, value.hex]));
  return acc;
}, {});

const css = `/* Generated by scripts/generate-docs-design.mjs via dk itself. Do not hand-edit. */
:root {
  --dk-seed: ${perfect.tokens.baseColor};
  --dk-primary: ${perfect.tokens.primaryHex};
  --dk-primary-ink: ${perfect.tokens.onPrimaryHex};
  --dk-surface: ${perfect.tokens.surfaceHex};
  --dk-ink: ${perfect.tokens.surfaceInk};
  --dk-outline: ${perfect.tokens.outlineHex};
  --dk-accent-a: ${perfect.tokens.accentA};
  --dk-accent-b: ${perfect.tokens.accentB};
  --dk-motion-curve: ${perfect.tokens.motionCurve};
  --dk-type-line-height: ${text.recommendation.lineHeight};
  --dk-type-word-spacing: ${text.recommendation.wordSpacingEm}em;
  --dk-type-measure: ${text.input.containerWidth}px;
  --dk-target-time: ${target.report.totalMs}ms;
  --dk-tone-primary-50: ${tones.primary['50']};
  --dk-tone-primary-100: ${tones.primary['100']};
  --dk-tone-primary-200: ${tones.primary['200']};
  --dk-tone-primary-400: ${tones.primary['400']};
  --dk-tone-primary-700: ${tones.primary['700']};
  --dk-tone-primary-900: ${tones.primary['900']};
  --dk-tone-secondary-100: ${tones.secondary['100']};
  --dk-tone-secondary-300: ${tones.secondary['300']};
  --dk-tone-secondary-500: ${tones.secondary['500']};
  --dk-tone-secondary-800: ${tones.secondary['800']};
  --dk-tone-tertiary-100: ${tones.tertiary['100']};
  --dk-tone-tertiary-300: ${tones.tertiary['300']};
  --dk-tone-tertiary-500: ${tones.tertiary['500']};
  --dk-tone-tertiary-800: ${tones.tertiary['800']};
${scale.scale.map((step) => `  ${step.token}: ${step.value};`).join('\n')}
}
`;

const data = {
  seed,
  perfect: {
    tokens: perfect.tokens,
    proofCards: perfect.proofCards,
    layout: perfect.layout,
    typography: perfect.typography
  },
  scale,
  text: text.recommendation,
  target,
  palette: {
    type: palette.type,
    colors: palette.colors.map((color) => ({ label: color.label, hex: color.hex }))
  }
};

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'dk-tokens.css'), css);
writeFileSync(join(outDir, 'dk-proof.json'), `${JSON.stringify(data, null, 2)}\n`);
console.log(`Generated docs design tokens from dk into ${outDir}`);
